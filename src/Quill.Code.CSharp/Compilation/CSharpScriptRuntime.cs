using Quill.Code.Scripting;
using System.Reflection;
using Quill.Code.CSharp.Constants;

namespace Quill.Code.CSharp.Compilation;

/// <summary>
/// Runtime des scripts (<see cref="CSharpLanguageOptions.IncludeScriptRuntime"/>) : <c>Log</c>, <c>LogLevel</c>
/// et <c>Script</c>, générés dans chaque assembly puis branchés par réflexion. Propres à chaque compilation : des
/// exécutions simultanées ne se mélangent pas, et le script ne référence aucune assembly de l'application.
/// </summary>
internal static class CSharpScriptRuntime
{
    // Espace de noms global : visible sans using, et prioritaire sur un type homonyme importé (pas d'ambiguïté).
    // Noms qualifiés : le source ne dépend ni des usings ni du contexte nullable du projet.
    public static string Source { get; } = $$"""
        // <auto-generated> Runtime des scripts Quill, branché par l'hôte. </auto-generated>
        #nullable enable

        /// <summary>Niveau d'un message de <see cref="Log"/>.</summary>
        internal enum LogLevel { {{string.Join(", ", Enum.GetNames<LogLevel>())}} }

        /// <summary>Journal du script, affiché par l'application.</summary>
        internal static class Log
        {
            private static global::System.Action<int, string>? Sink { get; set; }

            public static void Trace(object? value) => Write(LogLevel.Trace, value);

            public static void Debug(object? value) => Write(LogLevel.Debug, value);

            public static void Information(object? value) => Write(LogLevel.Information, value);

            public static void Warning(object? value) => Write(LogLevel.Warning, value);

            public static void Error(object? value) => Write(LogLevel.Error, value);

            public static void Critical(object? value) => Write(LogLevel.Critical, value);

            public static void Write(LogLevel level, object? value)
            {
                if (level is >= LogLevel.Trace and < LogLevel.None)
                    Sink?.Invoke((int)level, global::System.Convert.ToString(value) ?? string.Empty);
            }
        }

        /// <summary>Contexte d'exécution du script.</summary>
        internal static class Script
        {
            /// <summary>Signalé quand l'utilisateur annule : les boucles longues doivent le vérifier.</summary>
            public static global::System.Threading.CancellationToken CancellationToken { get; private set; }

            public static void ThrowIfCancellationRequested() => CancellationToken.ThrowIfCancellationRequested();
        }
        """;

    /// <summary>Dirige le <c>Log</c> de l'assembly vers <paramref name="log"/>.</summary>
    /// <exception cref="InvalidOperationException">Assembly compilée sans le runtime des scripts.</exception>
    public static void BindLog(Assembly assembly, Action<LogLevel, string> log)
    {
        var sink = FindProperty(assembly, "Log", "Sink")
            ?? throw new InvalidOperationException("CSharpCompileOptions.Log demande CSharpLanguageOptions.IncludeScriptRuntime.");

        // LogLevel du script : mêmes noms et valeurs que celui de Quill, dont il est généré.
        sink.SetValue(null, new Action<int, string>((level, text) => log((LogLevel)level, text)));
    }

    /// <summary>Fixe <c>Script.CancellationToken</c> ; sans effet sans le runtime des scripts.</summary>
    public static void SetCancellationToken(Assembly assembly, CancellationToken cancellationToken)
        => FindProperty(assembly, "Script", "CancellationToken")?.SetValue(null, cancellationToken);

    private static PropertyInfo? FindProperty(Assembly assembly, string typeName, string propertyName)
        => assembly.GetType(typeName)?.GetProperty(propertyName, CSharpScriptConstants.StaticMembers);
}
